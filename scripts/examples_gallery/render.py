"""Collect every example's row and write (or check) the gallery pages."""

from __future__ import annotations

import ast
import logging
import re
import sys
from collections.abc import Iterable, Sequence
from dataclasses import dataclass
from pathlib import Path
from typing import Any

import yaml

from scripts.examples_gallery.areas import AREAS, Area, GalleryError, area_of
from scripts.examples_gallery.install import install_line

logger = logging.getLogger(__name__)

ROOT = Path(__file__).resolve().parents[2]
EXAMPLES = ROOT / "examples"
DOCS = ROOT / "docs"
MKDOCS = ROOT / "mkdocs.yml"
SNIPPET = re.compile(r'--8<--\s+"(examples/[^":]+)')
HOME = "index.md"  # names almost every example; any other page explains it better
TEMPLATE_PREFIX = "template_"
TEMPLATE_RUN = re.compile(r"\s+(Run|Demo): .*$")
TOP_LEVEL_RUNS = {"print", "asyncio.run"}  # what makes a file without `__main__` runnable
SERVES = {"template_mcp_server": "over stdio, for an MCP host"}  # no port to detect
GENERATED = "<!-- Generated by scripts/gen_examples_gallery.py; edit the examples, not this. -->"


@dataclass(frozen=True)
class Example:
    rel: str  # path under examples/ without `.py`: "hello", "deploy/app"
    summary: str
    area: str
    install: str
    optional: str  # a second `pip install` for paths the demo does not take; "" for none
    run: str  # "" when running the file does nothing (an app, helper or classes)
    serves: str  # where its `__main__` serves until Ctrl+C ("on :8000"); "" when it exits
    docs: tuple[str, str] | None  # (docs-relative page, page title)


def page_path(area: Area | None) -> str:
    """The docs-relative path of the gallery index (None) or of an area page."""
    return "examples.md" if area is None else f"examples/{area.slug}.md"


def gallery_pages() -> list[str]:
    """Every page this generator writes, index first."""
    return [page_path(None), *(page_path(a) for a in AREAS)]


def example_files() -> list[Path]:
    """Every example script under examples/, caches excluded.

    examples/clients/ is left out: those clients run in Docker, one per language,
    with their own README.
    """
    clients = EXAMPLES / "clients"
    files = [
        p
        for p in EXAMPLES.rglob("*.py")
        if "__pycache__" not in p.parts and clients not in p.parents
    ]
    return sorted(files, key=lambda p: p.relative_to(EXAMPLES).as_posix())


def summary_of(tree: ast.Module, rel: str) -> str:
    """The module docstring's first line, safe inside a Markdown table cell."""
    doc = ast.get_docstring(tree)
    if not doc:
        raise GalleryError(f"examples/{rel}.py needs a module docstring")
    line = doc.splitlines()[0].strip().replace("|", "\\|")
    if rel.startswith(TEMPLATE_PREFIX):  # "... Run: python main.py" names the scaffolded file
        line = TEMPLATE_RUN.sub("", line) + " Scaffolded by `agent-adapter init`."
    return line


def _main_guard(tree: ast.Module) -> ast.If | None:
    for node in tree.body:
        if isinstance(node, ast.If) and "__main__" in ast.unparse(node.test):
            return node
    return None


def runnable(tree: ast.Module) -> bool:
    """True when running the file does something: a `__main__` guard or a top-level print."""
    if _main_guard(tree):
        return True
    return any(
        isinstance(node, ast.Expr)
        and isinstance(node.value, ast.Call)
        and ast.unparse(node.value.func) in TOP_LEVEL_RUNS
        for node in tree.body
    )


def serves(tree: ast.Module, rel: str) -> str:
    """Where `__main__` itself (not behind a flag) serves: `<server>.run(..., port=N)`."""
    if rel in SERVES:
        return SERVES[rel]
    guard = _main_guard(tree)
    for node in guard.body if guard else []:
        call = node.value if isinstance(node, ast.Expr) else None
        if isinstance(call, ast.Call) and isinstance(call.func, ast.Attribute):
            for keyword in call.keywords if call.func.attr == "run" else []:
                port = keyword.value.value if isinstance(keyword.value, ast.Constant) else None
                if keyword.arg == "port" and isinstance(port, int):
                    return f"on :{port}"
    return ""


def _flatten(nav: Any) -> Iterable[str]:
    if isinstance(nav, str):
        yield nav
    elif isinstance(nav, list):
        for item in nav:
            yield from _flatten(item)
    elif isinstance(nav, dict):
        for value in nav.values():
            yield from _flatten(value)


def nav_pages() -> list[str]:
    """Docs pages in nav order; the nav is parsed alone because the rest uses Python tags."""
    text = MKDOCS.read_text(encoding="utf-8")
    return list(_flatten(yaml.safe_load(text[text.index("\nnav:\n") :])["nav"]))


def docs_pages() -> dict[str, str]:
    """Published pages and their text: nav order, then the rest sorted, the home page last."""
    found = {
        p.relative_to(DOCS).as_posix()
        for p in DOCS.rglob("*.md")
        if "superpowers" not in p.relative_to(DOCS).parts
    }
    found -= {*gallery_pages(), HOME}
    ordered = [p for p in nav_pages() if p in found]
    pages = [*ordered, *sorted(found - set(ordered)), HOME]
    return {p: (DOCS / p).read_text(encoding="utf-8") for p in pages if (DOCS / p).is_file()}


def title_of(text: str, page: str) -> str:
    """A page's H1, or its path when it has none."""
    for line in text.splitlines():
        if line.startswith("# "):
            return line[2:].strip()
    return page


def page_for(rel: str, pages: dict[str, str]) -> tuple[str, str] | None:
    """The first page that includes the example as a snippet, else the first that names it."""
    target = f"examples/{rel}.py"
    named = re.compile(re.escape(target) + r"(?![\w/])")
    for match in (lambda text: target in SNIPPET.findall(text), named.search):
        for page, text in pages.items():
            if match(text):
                return page, title_of(text, page)
    return None


def collect() -> list[Example]:
    """Every example's row; raises GalleryError for one that cannot be placed."""
    pages = docs_pages()
    examples = []
    for path in example_files():
        rel = path.relative_to(EXAMPLES).with_suffix("").as_posix()
        tree = ast.parse(path.read_text(encoding="utf-8"))
        install, optional = install_line(rel)
        examples.append(
            Example(
                rel=rel,
                summary=summary_of(tree, rel),
                area=area_of(rel),
                install=install,
                optional=optional,
                run=f"python examples/{rel}.py" if runnable(tree) else "",
                serves=serves(tree, rel),
                docs=page_for(rel, pages),
            )
        )
    return examples


def render_index(examples: Sequence[Example]) -> str:
    """docs/examples.md: how to run an example, and the index by area."""
    lines = [
        "# Examples gallery",
        "",
        GENERATED,
        "",
        "Every example file under `examples/`, grouped by area.",
        f"There are {len(examples)}. They need no network and no API keys: fakes stand in",
        "for models and remote services.",
        "",
        "## Run one",
        "",
        "1. Install what its row names. `pip install agent-adapter` is the core alone.",
        "   An *optional* line adds only the parts the default run skips.",
        "2. From the repository root, run `python examples/<file>.py`.",
        "3. Read the docs page in its row: it explains the snippets.",
        "",
        "A row marked *starts a server* serves on localhost until you press Ctrl+C.",
        "A row without a run command is *import only*: an app object, a shared helper or",
        "classes that other code imports. Its docs page shows how to start it.",
        "",
        "## Index by area",
        "",
        '<div class="aa-gallery" markdown>',
    ]
    for area in AREAS:
        count = sum(1 for e in examples if e.area == area.slug)
        card = f"<b>{area.title}</b><span>{area.blurb}</span><small>{count} examples</small>"
        lines.append(f"[{card}]({page_path(area)}){{ .aa-gcard }}")
    lines.append("</div>")
    return "\n".join(lines) + "\n"


def _row(example: Example) -> str:
    install = f"`{example.install}`"
    if example.optional:
        install += f"; optional: `{example.optional}`"
    run = f"`{example.run}`" if example.run else "import only"
    if example.run and example.serves:
        run += f" (starts a server {example.serves})"
    docs = f"[{example.docs[1]}](../{example.docs[0]})" if example.docs else "-"
    return f"| `examples/{example.rel}.py` | {example.summary} | {install} | {run} | {docs} |"


def render_area(area: Area, examples: Sequence[Example]) -> str:
    """docs/examples/<slug>.md: one row per example in the area."""
    rows = [_row(e) for e in examples if e.area == area.slug]
    lines = [
        f"# Examples: {area.title.lower()}",
        "",
        GENERATED,
        "",
        f"{area.blurb} Back to the [Examples gallery](../examples.md). Files here: {len(rows)}.",
        "",
        "| File | Shows | Install | Run | Docs |",
        "|---|---|---|---|---|",
        *rows,
    ]
    return "\n".join(lines) + "\n"


def render() -> dict[Path, str]:
    """Every gallery file and its text."""
    examples = collect()
    files = {DOCS / page_path(None): render_index(examples)}
    for area in AREAS:
        files[DOCS / page_path(area)] = render_area(area, examples)
    return files


def _differs(path: Path, text: str) -> bool:
    return not path.is_file() or path.read_text(encoding="utf-8") != text


def stale() -> list[Path]:
    """The gallery files whose content differs from `render()`."""
    return [path for path, text in render().items() if _differs(path, text)]


def write() -> list[Path]:
    """Write every gallery file that changed; return them."""
    changed = []
    for path, text in render().items():
        if _differs(path, text):
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8", newline="\n")
            logger.info("wrote %s", path.relative_to(ROOT).as_posix())
            changed.append(path)
    return changed


def main(argv: Sequence[str] | None = None) -> int:
    """`--check` exits 1 when a gallery file is stale; otherwise write them all."""
    logging.basicConfig(level=logging.INFO, format="%(message)s")
    args = list(sys.argv[1:] if argv is None else argv)
    if args not in ([], ["--check"]):
        logger.error("usage: python scripts/gen_examples_gallery.py [--check]")
        return 2
    try:
        changed = stale() if args else write()
    except GalleryError as exc:
        logger.error("%s", exc)
        return 1
    if not args:
        return 0
    for path in changed:
        logger.error("stale: %s", path.relative_to(ROOT).as_posix())
    return 1 if changed else 0
