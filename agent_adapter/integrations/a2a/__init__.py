class A2AIntegration(IntegrationBase):
    """Exports one `AgentSkill` per tool; `a2a_app` / `a2a_executor` run the calls."""

    name = TARGET
    requires = ("a2a",)
    extra = "a2a"
    call_id_fields = ("task_id",)  # the A2A task id, generated by the server

    def export_tool(self, spec: ToolSpec, *, executor: ToolRunner | None = None) -> AgentSkill:
        """The skill for `spec`; `executor` is used by `a2a_app`, not here."""
        return agent_skill(spec)


INTEGRATION = A2AIntegration()
